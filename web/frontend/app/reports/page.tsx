'use client';
import { useEffect, useState } from 'react';
const API = 'http://localhost:8080';

interface CondRow { condition: string; accuracy: string; trustworthiness_index: string; hallucination_rate: string; bias_rate: string; robustness_score: string; attack_success_rate: string; }
interface StatRow { metric: string; baseline_mean: string; target_mean: string; mean_difference_target_minus_baseline: string; ci95_low: string; ci95_high: string; p_value: string; holm_adjusted_p_value: string; }
interface ModelRow { rank: number; algorithm: string; activation: string; test_accuracy: number; test_f1: number; test_auc: number; parameters: number; }

export default function ReportsPage() {
  const [runs, setRuns] = useState<{run_id:string}[]>([]);
  const [selectedRun, setSelectedRun] = useState('');
  const [condRows, setCondRows] = useState<CondRow[]>([]);
  const [statRows, setStatRows] = useState<StatRow[]>([]);
  const [models, setModels] = useState<ModelRow[]>([]);
  const [manifest, setManifest] = useState<Record<string,unknown>>({});
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    Promise.all([
      fetch(`${API}/api/experiments`).then(r=>r.json()),
      fetch(`${API}/api/deep-learning/models`).then(r=>r.json()),
      fetch(`${API}/api/deep-learning/manifest`).then(r=>r.json()),
    ]).then(([r, m, mf]) => {
      setRuns(r);
      setModels(m.sort((a:ModelRow,b:ModelRow)=>a.rank-b.rank));
      setManifest(mf);
      if (r.length) setSelectedRun(r[r.length-1].run_id);
      setLoading(false);
    }).catch(()=>setLoading(false));
  }, []);

  useEffect(() => {
    if (!selectedRun) return;
    Promise.all([
      fetch(`${API}/api/experiments/${selectedRun}/condition-metrics`).then(r=>r.json()),
      fetch(`${API}/api/experiments/${selectedRun}/statistical-tests`).then(r=>r.json()),
    ]).then(([c,s])=>{setCondRows(c);setStatRows(s);}).catch(()=>{});
  }, [selectedRun]);

  function downloadReport() {
    const baseline = condRows.find(r=>r.condition==='baseline');
    const full = condRows.find(r=>r.condition==='full_mitcf');
    const topModel = models[0];
    const date = new Date().toISOString().split('T')[0];
    const content = `# MITCF Experimental Report\n**Generated:** ${date}\n**Run:** ${selectedRun}\n\n---\n\n## 1. Executive Summary\n\nThe MITCF (Modular Inference-Time Control Framework) improves trustworthiness from TI=${parseFloat(baseline?.trustworthiness_index??'0').toFixed(3)} (baseline) to TI=${parseFloat(full?.trustworthiness_index??'0').toFixed(3)} (full_mitcf), an improvement of +${(parseFloat(full?.trustworthiness_index??'0')-parseFloat(baseline?.trustworthiness_index??'0')).toFixed(3)}.\n\nAccuracy improves from ${(parseFloat(baseline?.accuracy??'0')*100).toFixed(1)}% to ${(parseFloat(full?.accuracy??'0')*100).toFixed(1)}%.\n\n## 2. Deep Learning Results\n\nTop model: ${topModel?.algorithm} (${topModel?.activation}, ${topModel?.parameters?.toLocaleString()} params)\n- Test Accuracy: ${(topModel?.test_accuracy*100).toFixed(1)}%\n- Test F1: ${(topModel?.test_f1*100).toFixed(1)}%\n- Test AUC: ${topModel?.test_auc?.toFixed(4)}\n\n## 3. Condition Comparison\n\n| Condition | Accuracy | TI | Hall. Rate | Robustness |\n|---|---|---|---|---|\n${condRows.map(r=>`| ${r.condition} | ${(parseFloat(r.accuracy)*100).toFixed(1)}% | ${parseFloat(r.trustworthiness_index).toFixed(3)} | ${(parseFloat(r.hallucination_rate)*100).toFixed(1)}% | ${parseFloat(r.robustness_score).toFixed(3)} |`).join('\n')}\n\n## 4. Statistical Tests (Holm–Bonferroni adjusted)\n\n| Metric | Baseline | Full MITCF | Diff | CI95 | Holm p |\n|---|---|---|---|---|---|\n${statRows.map(r=>`| ${r.metric} | ${parseFloat(r.baseline_mean).toFixed(4)} | ${parseFloat(r.target_mean).toFixed(4)} | ${parseFloat(r.mean_difference_target_minus_baseline)>0?'+':''}${parseFloat(r.mean_difference_target_minus_baseline).toFixed(4)} | [${parseFloat(r.ci95_low).toFixed(3)}, ${parseFloat(r.ci95_high).toFixed(3)}] | ${parseFloat(r.holm_adjusted_p_value).toFixed(4)} |`).join('\n')}\n\n---\n*Generated by MITCF Web Platform*\n`;
    const blob = new Blob([content], {type:'text/markdown'});
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = `mitcf_report_${selectedRun}.md`; a.click();
    URL.revokeObjectURL(url);
  }

  if (loading) return <div className="text-sm" style={{ color:'var(--text-muted)' }}>Loading report data...</div>;

  return (
    <div>
      <div className="mb-6">
        <h2 className="text-xl font-bold" style={{ color:'var(--text-primary)' }}>Reports</h2>
        <p className="text-sm mt-1" style={{ color:'var(--text-muted)' }}>
          Generate and export experiment reports from actual project outputs.
        </p>
      </div>

      <div className="flex items-center gap-3 mb-4">
        <label className="text-xs" style={{ color:'var(--text-muted)' }}>Run:</label>
        <select value={selectedRun} onChange={e=>setSelectedRun(e.target.value)}
          className="text-xs px-2 py-1 rounded" style={{ background:'var(--bg-card)', border:'1px solid var(--border)', color:'var(--text-primary)' }}>
          {runs.map(r=><option key={r.run_id} value={r.run_id}>{r.run_id}</option>)}
        </select>
        <button onClick={downloadReport}
          className="btn-primary px-4 py-1.5 rounded text-sm" style={{ marginLeft:'auto' }}>
          ↓ Download Markdown Report
        </button>
      </div>

      {/* Report preview */}
      <div className="kpi-card">
        <h3 className="text-sm font-semibold mb-4" style={{ color:'var(--text-primary)' }}>Report Preview</h3>

        <div className="space-y-6">
          {/* Executive summary */}
          {condRows.length > 0 && (() => {
            const base = condRows.find(r=>r.condition==='baseline');
            const full = condRows.find(r=>r.condition==='full_mitcf');
            if (!base||!full) return null;
            const tiDelta = parseFloat(full.trustworthiness_index)-parseFloat(base.trustworthiness_index);
            const accDelta = parseFloat(full.accuracy)-parseFloat(base.accuracy);
            return (
              <div>
                <h4 className="text-xs font-semibold mb-2" style={{ color:'var(--accent)' }}>1. Executive Summary</h4>
                <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
                  {[
                    { label:'TI Improvement', val:`+${tiDelta.toFixed(3)}`, color:'#22c55e' },
                    { label:'Accuracy Gain', val:`+${(accDelta*100).toFixed(1)}pp`, color:'#22c55e' },
                    { label:'Full MITCF TI', val:parseFloat(full.trustworthiness_index).toFixed(3), color:'#3b82f6' },
                    { label:'Hallucination Eliminated', val:`${(parseFloat(full.hallucination_rate)*100).toFixed(0)}%`, color:'#22c55e' },
                  ].map(item=>(
                    <div key={item.label} className="p-3 rounded text-center" style={{ background:`${item.color}10`, border:`1px solid ${item.color}30` }}>
                      <div className="text-xs" style={{ color:'var(--text-muted)', fontSize:'10px' }}>{item.label}</div>
                      <div className="text-xl font-bold" style={{ color:item.color }}>{item.val}</div>
                    </div>
                  ))}
                </div>
              </div>
            );
          })()}

          {/* Top models */}
          {models.length > 0 && (
            <div>
              <h4 className="text-xs font-semibold mb-2" style={{ color:'var(--accent)' }}>2. Deep Learning — Top 5 Models</h4>
              <table className="data-table">
                <thead><tr><th>Rank</th><th>Algorithm</th><th>Activation</th><th>Params</th><th>Test Acc</th><th>F1</th><th>AUC</th></tr></thead>
                <tbody>
                  {models.slice(0,5).map(m=>(
                    <tr key={m.algorithm}>
                      <td>#{m.rank}</td>
                      <td className="font-mono text-xs">{m.algorithm}</td>
                      <td>{m.activation}</td>
                      <td>{m.parameters.toLocaleString()}</td>
                      <td style={{ color:m.test_accuracy>=0.8?'#22c55e':'#f59e0b', fontWeight:600 }}>{(m.test_accuracy*100).toFixed(1)}%</td>
                      <td>{(m.test_f1*100).toFixed(1)}%</td>
                      <td>{m.test_auc.toFixed(4)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          {/* Statistical significance */}
          {statRows.length > 0 && (
            <div>
              <h4 className="text-xs font-semibold mb-2" style={{ color:'var(--accent)' }}>3. Statistical Significance</h4>
              <table className="data-table">
                <thead><tr><th>Metric</th><th>Diff</th><th>95% CI</th><th>Holm p</th><th>Sig</th></tr></thead>
                <tbody>
                  {statRows.map(s=>{
                    const p=parseFloat(s.holm_adjusted_p_value);
                    const diff=parseFloat(s.mean_difference_target_minus_baseline);
                    return (
                      <tr key={s.metric}>
                        <td className="font-mono text-xs">{s.metric}</td>
                        <td style={{ color:diff>0?'#22c55e':'#ef4444', fontWeight:600 }}>{diff>0?'+':''}{diff.toFixed(4)}</td>
                        <td className="font-mono text-xs">[{parseFloat(s.ci95_low).toFixed(3)}, {parseFloat(s.ci95_high).toFixed(3)}]</td>
                        <td className="font-mono text-xs">{p.toFixed(4)}</td>
                        <td style={{ color:p<0.01?'#22c55e':p<0.05?'#f59e0b':'#64748b', fontWeight:700 }}>{p<0.01?'**':p<0.05?'*':'ns'}</td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
